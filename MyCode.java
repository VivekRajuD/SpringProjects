public class MyCode {
    public static void main(String[] args) {
        int num1 = 5;
        int num2 = 7;
        int result = multiply(num1, num2);
        System.out.println(num1 + " * " + num2 + " = " + result);
    }

    public static int multiply(int a, int b) {
        return a * b;
    }
}
